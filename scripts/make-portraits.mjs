#!/usr/bin/env node
/**
 * Makes small web portraits for the people shown on the site (team, advisory board, community),
 * from the original photos in public/ that data/members.ts points to. The originals stay as they
 * are; the site loads public/portraits/<id>.jpg (480 px, about 30 KB) instead of multi-MB files.
 * Writes lib/portraits.ts, the list of members that have a portrait. Members added later through
 * /add-member fall back to their original photo until this is run again.
 *
 * Local tool (uses macOS `sips`):  node scripts/make-portraits.mjs
 */
import { execFileSync } from "node:child_process"
import { existsSync, mkdirSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import { advisoryBoardMembers, communityMembers, foundingTeamMembers } from "../data/members.ts"

const root = resolve(new URL("..", import.meta.url).pathname)
const out = join(root, "public/portraits")
mkdirSync(out, { recursive: true })

const done = []
const seen = new Set()
for (const m of [...foundingTeamMembers, ...advisoryBoardMembers, ...communityMembers]) {
  if (seen.has(m.id) || !m.imageSrc?.startsWith("/")) continue
  seen.add(m.id)
  const src = join(root, "public", decodeURI(m.imageSrc))
  if (!existsSync(src)) {
    console.warn(`no photo for ${m.name}: ${m.imageSrc}`)
    continue
  }
  const dest = join(out, `${m.id}.jpg`)
  try {
    execFileSync("sips", ["-s", "format", "jpeg", "-s", "formatOptions", "72", "-Z", "480", src, "--out", dest], { stdio: "ignore" })
    done.push(m.id)
  } catch {
    console.warn(`could not convert ${m.imageSrc}`)
  }
}

writeFileSync(
  join(root, "lib/portraits.ts"),
  `/* Generated by scripts/make-portraits.mjs. Do not edit by hand. */
/** Members (by id in data/members.ts) with a small portrait in public/portraits/<id>.jpg. */
export const PORTRAITS: ReadonlySet<string> = new Set(${JSON.stringify(done.sort())})
`,
)
console.log(`portraits: ${done.length}`)
